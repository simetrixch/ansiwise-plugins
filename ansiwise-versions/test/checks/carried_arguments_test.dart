import 'package:ansiwise_checks/audits.dart';

/// carried-arguments — what a row grants this package's steps is carried all the way to the act.
///
/// The mirror of declared-arguments. First hop: a step that READS an argument it does not DECLARE
/// never receives the value — `has` answers no and the step quietly does without. Second hop: a
/// file carrying the elevation in a field or in a parameter passes it to every call that reaches
/// the machine — a files-port call and a composed command alike — or that one call acts as the
/// operator. Each shape cost a real machine run to find on one day.
void main() => auditCarriedArguments(scannedPaths: <String>['lib']);
